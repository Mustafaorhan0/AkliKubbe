async (page) => {
  const results=[];
  const check=async(name, ok)=>{results.push({name,passed:!!ok});await page.evaluate(r=>sessionStorage.setItem('aklikubbe-test-report',JSON.stringify(r)),results);if(!ok)throw new Error(name);};
  await page.context().setOffline(false);
  await page.goto('http://localhost:4173');
  await page.evaluate(()=>localStorage.removeItem('aklikubbe.v1'));
  await page.reload();
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#deck').selectOption('legacy');
  await page.waitForFunction(()=>document.querySelector('#word-image')?.naturalWidth>0,{timeout:22000});
  await check('Canlı Wikimedia görseli',await page.locator('#word-image').count()===1);
  await page.locator('#flip').click();
  await page.waitForSelector('#save-sentence',{timeout:22000});
  await check('Canlı üç dilli Tatoeba örneği',await page.locator('.sentence-row .missing').count()===0);
  await page.locator('#save-sentence').click();
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('aklikubbe.v1')).saved[0]);
  await page.locator('#next-example').click();
  await check('Kaydedilmiş örnek değişmez',await page.evaluate(text=>JSON.parse(localStorage.getItem('aklikubbe.v1')).saved[0].sentences[0].text===text,saved.sentences[0].text));
  await page.locator('#unknown').click();
  await check('Bilinmeyen kutusuna kayıt',await page.evaluate(()=>JSON.parse(localStorage.getItem('aklikubbe.v1')).learning.Q89.status==='unknown'));
  await page.locator('#undo').click();
  await check('Sınıflandırmayı geri alma',await page.locator('.word-title h2').innerText()==='elma' && await page.evaluate(()=>!JSON.parse(localStorage.getItem('aklikubbe.v1')).learning.Q89));
  await page.locator('#known').click();
  await page.reload();
  await page.locator('#deck').selectOption('legacy');
  await check('Yeniden açılışta kayıt korunur',await page.evaluate(()=>JSON.parse(localStorage.getItem('aklikubbe.v1')).learning.Q89.status==='known'));
  await page.locator('.sidebar [data-nav="known"]').click();
  await check('Bilinenleri listeleme',await page.locator('.list-word').count()===1);
  await page.locator('[data-move="Q89"]').click();
  await page.locator('.sidebar [data-nav="unknown"]').click();
  await check('Kutular arasında taşıma',await page.locator('.list-word').count()===1);
  await page.locator('#review-collection').click();
  await check('Bilinmeyenleri tekrar oturumu',await page.locator('.word-title h2').innerText()==='elma');
  await page.locator('#flip').click();
  await page.waitForSelector('#save-sentence',{timeout:22000});
  await check('Aynı cümle tekrar kaydedilemez',await page.locator('#save-sentence').isDisabled());
  await page.setViewportSize({width:390,height:844});
  await check('Telefon arka yüzünde yatay taşma yok',await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth));
  await page.locator('.mobile-nav [data-nav="saved"]').click();
  await check('Mobil defterde kayıt görünür',await page.locator('.saved-card').count()===1);
  await check('Telefon defterinde yatay taşma yok',await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth));
  await page.context().setOffline(true);
  await page.reload();
  await page.locator('.mobile-nav [data-nav="saved"]').click();
  await check('Çevrimdışı yeniden açılış ve kayıtlı cümle',await page.locator('.saved-card').innerText().then(t=>t.includes(saved.sentences[0].text)));
  await check('Uygulama önbelleğinde uzak görseller yok',await page.evaluate(async()=>{for(const key of await caches.keys()){const c=await caches.open(key);if((await c.keys()).some(r=>!r.url.startsWith(location.origin+'/')))return false;}return true;}));
  await page.context().setOffline(false);
  await page.locator('.mobile-nav [data-nav="settings"]').click();
  const download=page.waitForEvent('download');await page.locator('#export').click();
  const file=await download;
  await check('Yedek dışa aktarma',file.suggestedFilename().endsWith('.json'));
  // Test verileri yalnızca bu yerel test tarayıcısında oluşturulur.
  await page.evaluate(()=>{window.confirm=()=>true;});
  await page.locator('#reset').click();
  await page.locator('.mobile-nav [data-nav="study"]').click();
  await page.locator('#deck').selectOption('legacy');
  await page.locator('#search').fill('kedi');
  await check('Türkçe kelime araması',await page.locator('.word-title h2').innerText()==='kedi');
  await page.locator('#search').fill('');
  const bounds=await page.locator('#word-card').boundingBox();
  await page.mouse.move(bounds.x+40,bounds.y+100);
  await page.mouse.down();await page.mouse.move(bounds.x+180,bounds.y+100,{steps:8});await page.mouse.up();
  await check('Sağa kaydırarak sınıflandırma',await page.evaluate(()=>JSON.parse(localStorage.getItem('aklikubbe.v1')).learning.Q89.status==='known'));
  await page.locator('#undo').click();
  await page.locator('.mobile-nav [data-nav="settings"]').click();
  await page.evaluate(()=>{window.confirm=()=>true;});
  await page.locator('#import').setInputFiles({name:'aklikubbe-yedek.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({version:1,learning:{Q89:{status:'known',updatedAt:100}},saved:[saved]}))});
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('aklikubbe.v1')).saved.length===1);
  await check('Yedeği içe aktarma',await page.evaluate(()=>JSON.parse(localStorage.getItem('aklikubbe.v1')).saved.length===1));
  await page.locator('#import').setInputFiles({name:'bozuk.json',mimeType:'application/json',buffer:Buffer.from('{bad json')});
  await page.waitForFunction(()=>document.querySelector('#toast').innerText.includes('Yedek yüklenemedi'));
  await check('Bozuk yedek mevcut veriyi değiştirmez',await page.evaluate(()=>JSON.parse(localStorage.getItem('aklikubbe.v1')).saved.length===1));
  await page.evaluate(()=>localStorage.removeItem('aklikubbe.v1'));
  await page.reload();
  await page.setViewportSize({width:1440,height:1000});
  return results;
}
